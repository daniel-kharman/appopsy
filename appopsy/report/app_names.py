"""Friendly names for widely used apps, from Wikidata (CC0).

`app_names.tsv` is generated by `scripts/update_app_names.py` from Wikidata's
"Google Play Store app ID" property (P3418) and never edited by hand. Format: a
`#` header (source, licence, retrieval date, the exact query, the rules), then
one row per package, `package<TAB>name<TAB>Wikidata ID`, sorted by package with
no duplicates.

Labels come from Wikidata, which anyone can edit, so they are untrusted: a row
whose name isn't short printable plain text is rejected here, by the generator,
by `--verify` and by the format test. The file is the one exemption from the
local "your apps" check (see `redact.scan_tree`), and only while it validates.

Display names only: redaction never treats these apps as public, because which
widely used apps you have (dating, health, religious, political ...) is personal.
"""

from __future__ import annotations

import functools
import re
from dataclasses import dataclass
from importlib import resources

PATH_IN_REPO = "appopsy/report/app_names.tsv"
MIN_ROWS = 5000  # it's the whole public set, never a short hand-picked list
MAX_LABEL = 60
QUERY = (
    "SELECT ?item ?id ?en ?mul ?links WHERE { ?item wdt:P3418 ?id . "
    'OPTIONAL { ?item rdfs:label ?en FILTER(LANG(?en) = "en") } '
    'OPTIONAL { ?item rdfs:label ?mul FILTER(LANG(?mul) = "mul") } '
    "OPTIONAL { ?item wikibase:sitelinks ?links } }"
)
REQUIRED_HEADER = ("# Source: Wikidata", "# Licence: CC0 1.0", f"# Query: {QUERY}")

_PACKAGE = re.compile(r"[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z0-9_]+)+")
_QID = re.compile(r"Q[1-9][0-9]*")
# Characters that are markup in Markdown or HTML, or that tables and shells treat
# specially. Names of real apps don't need them.
_FORBIDDEN = frozenset("<>[]{}|\\`*_#~$")


def label_problem(label: str) -> str | None:
    """Why an (untrusted) label can't be shown, or None if it can."""
    if not label:
        return "empty name"
    if len(label) > MAX_LABEL:
        return f"name longer than {MAX_LABEL} characters"
    if not label.isprintable():
        return "name has control or non-printable characters"
    if label != label.strip() or "  " in label:
        return "name has stray whitespace"
    if _FORBIDDEN & set(label):
        return "name has markup characters"
    if "://" in label or label.lower().startswith("www."):
        return "name looks like a link"
    return None


def row_problem(package: str, name: str, qid: str) -> str | None:
    """Why a row can't be used, or None. Shared by the loader, generator and checks."""
    if not _PACKAGE.fullmatch(package):
        return "not a package name"
    if not _QID.fullmatch(qid):
        return "not a Wikidata ID"
    return label_problem(name)


@dataclass(frozen=True)
class Row:
    line: int
    package: str
    name: str
    qid: str


def parse(text: str) -> tuple[list[str], list[Row], list[str]]:
    """(header lines, rows, problems). Problems are reported with line numbers only,
    never the offending text."""
    header: list[str] = []
    rows: list[Row] = []
    problems: list[str] = []
    for n, line in enumerate(text.splitlines(), start=1):
        if line.startswith("#"):
            if rows:
                problems.append(f"line {n}: header line after the rows")
            header.append(line)
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            problems.append(f"line {n}: not three tab-separated fields")
            continue
        package, name, qid = parts
        if (why := row_problem(package, name, qid)) is not None:
            problems.append(f"line {n}: {why}")
        else:
            rows.append(Row(n, package, name, qid))
    packages = [r.package for r in rows]
    if packages != sorted(packages):
        problems.append("rows not sorted by package")
    if len(set(packages)) != len(packages):
        problems.append("duplicate packages")
    for required in REQUIRED_HEADER:
        # The query must be exactly the one the generator runs; the rest by prefix.
        exact = required.startswith("# Query:")
        if not any(h == required if exact else h.startswith(required) for h in header):
            problems.append(f"header lacks {required.split(':')[0][2:]!r}")
    if len(rows) < MIN_ROWS:
        problems.append(f"only {len(rows)} rows (at least {MIN_ROWS})")
    return header, rows, problems


def validate(text: str) -> list[str]:
    return parse(text)[2]


def bundled_text() -> str:
    return (resources.files("appopsy.report") / "app_names.tsv").read_text(encoding="utf-8")


@functools.cache
def names() -> dict[str, str]:
    """package -> name. Empty if the bundled file doesn't validate (fail closed)."""
    try:
        _, rows, problems = parse(bundled_text())
    except (FileNotFoundError, UnicodeDecodeError):
        return {}
    return {} if problems else {r.package: r.name for r in rows}
