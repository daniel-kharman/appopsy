#!/usr/bin/env python3
"""Generate or verify appopsy/report/app_names.tsv from Wikidata (CC0).

    uv run python scripts/update_app_names.py            # regenerate the file
    uv run python scripts/update_app_names.py --verify   # check the file against Wikidata

Generation takes every Wikidata item with a "Google Play Store app ID" (P3418);
nothing is selected by hand and nothing is derived from anyone's own app list.
Rules, recorded in the file's header:
- name: the English label, else the multilingual ("mul") label;
- a trailing " app", " Android app", " for Android", "(app)" or "(Android)" is
  removed ("Facebook app" -> "Facebook");
- an ID on several items goes to the item with the most Wikipedia articles, ties
  to the lowest item number;
- rows whose package or name fails the checks in appopsy.report.app_names are
  dropped (names are untrusted: at most 60 printable characters, no markup).

--verify checks that the file validates, that every row's (package, Wikidata ID)
pair exists on Wikidata now, and that the file holds at least 95% of the rows a
fresh generation would: a change to the file can't add an app that isn't in the
public source, or cut the set down to a revealing subset. It prints counts only.
Exit status: 0 ok, 1 failed, 2 Wikidata couldn't be reached (also a failure for
the pre-push hook). Updates to the file only land through a pull request.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

from appopsy import __version__
from appopsy.report.app_names import MAX_LABEL, PATH_IN_REPO, QUERY, parse, row_problem

ENDPOINT = "https://query.wikidata.org/sparql"
# Wikimedia's policy asks for an identifying User-Agent with a contact URL.
USER_AGENT = f"appopsy/{__version__} (https://github.com/daniel-kharman/appopsy)"
COVERAGE = 0.95
# Whole words only: "Facebook app" -> "Facebook", but "WhatsApp" stays.
_SUFFIX = re.compile(
    r"(?:\s+(?:Android app|for Android|app)|\s*\((?:app|Android|Android app)\))$", re.I
)
ROOT = Path(__file__).resolve().parent.parent


def fetch(attempts: int = 4) -> list[dict[str, str]]:
    """Run QUERY. Wikidata rate-limits (429) and sheds load (503): wait as told by
    Retry-After (or back off) and try again, a few times."""
    url = f"{ENDPOINT}?{urllib.parse.urlencode({'query': QUERY})}"
    headers = {"Accept": "application/sparql-results+json", "User-Agent": USER_AGENT}
    for attempt in range(attempts):
        request = urllib.request.Request(url, headers=headers)  # noqa: S310 - fixed https URL
        try:
            with urllib.request.urlopen(request, timeout=120) as response:  # noqa: S310
                data = json.load(response)
            return [{k: v["value"] for k, v in b.items()} for b in data["results"]["bindings"]]
        except urllib.error.HTTPError as exc:
            if exc.code not in (429, 503) or attempt == attempts - 1:
                raise
            retry = exc.headers.get("Retry-After", "")
            time.sleep(min(int(retry) if retry.isdigit() else 10 * (attempt + 1), 120))
    raise AssertionError("unreachable")


def clean(label: str) -> str:
    name = _SUFFIX.sub("", label.strip()).strip()
    return name or label.strip()


def generate(
    bindings: list[dict[str, str]],
) -> tuple[dict[str, tuple[str, str]], set[tuple[str, str]], int]:
    """(package -> (name, qid), every (package, qid) pair on Wikidata, rows dropped)."""
    best: dict[str, tuple[int, int, str, str]] = {}  # package -> (-links, qnum, qid, name)
    pairs: set[tuple[str, str]] = set()
    for b in bindings:
        package = b["id"].strip()
        qid = b["item"].rsplit("/", 1)[-1]
        pairs.add((package, qid))
        label = b.get("en") or b.get("mul") or ""
        key = (-int(b.get("links", "0") or 0), int(qid[1:]), qid, clean(label))
        if package not in best or key < best[package]:
            best[package] = key
    rows: dict[str, tuple[str, str]] = {}
    dropped = 0
    for package, (_, _, qid, name) in best.items():
        if row_problem(package, name, qid) is None:
            rows[package] = (name, qid)
        else:
            dropped += 1
    return rows, pairs, dropped


def render(rows: dict[str, tuple[str, str]], dropped: int) -> str:
    header = [
        "# Friendly names for widely used Android apps. Generated by "
        "scripts/update_app_names.py; do not edit by hand (regenerate and open a PR).",
        '# Source: Wikidata (https://www.wikidata.org), property P3418 "Google Play Store app ID".',
        "# Licence: CC0 1.0 (public domain), https://creativecommons.org/publicdomain/zero/1.0/",
        f"# Retrieved: {date.today().isoformat()}. Rows: {len(rows)}. "
        f"Dropped by the name checks: {dropped}.",
        '# Rules: English label, else the multilingual label; trailing " app", " Android app", '
        '" for Android", "(app)", "(Android)" removed; an ID on several items goes to the item '
        f"with most Wikipedia articles, ties to the lowest item number; names at most {MAX_LABEL} "
        "printable characters without markup.",
        f"# Query: {QUERY}",
    ]
    body = [f"{p}\t{name}\t{qid}" for p, (name, qid) in sorted(rows.items())]
    return "\n".join(header + body) + "\n"


def verify(path: Path) -> int:
    _, rows, problems = parse(path.read_text(encoding="utf-8"))
    if problems:
        print(f"app names: {path.name} doesn't validate ({len(problems)} problem(s)); "
              f"first: {problems[0]}")  # fmt: skip
        return 1
    try:
        fresh, pairs, _ = generate(fetch())
    except OSError as exc:
        print(f"app names: couldn't reach Wikidata ({type(exc).__name__}); can't verify.")
        return 2
    unknown = sum((r.package, r.qid) not in pairs for r in rows)
    coverage = len(rows) / max(len(fresh), 1)
    print(f"app names: {len(rows)} rows, {unknown} not on Wikidata, "
          f"{coverage:.1%} of a fresh generation.")  # fmt: skip
    return 0 if unknown == 0 and coverage >= COVERAGE else 1


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--verify", action="store_true", help="check the file instead of writing it"
    )
    parser.add_argument("file", nargs="?", type=Path, default=ROOT / PATH_IN_REPO)
    args = parser.parse_args()
    if args.verify:
        return verify(args.file)
    rows, _, dropped = generate(fetch())
    text = render(rows, dropped)
    problems = parse(text)[2]
    if problems:
        print(f"app names: generated file doesn't validate: {problems[0]}")
        return 1
    args.file.write_text(text, encoding="utf-8")
    print(f"app names: wrote {len(rows)} rows ({dropped} dropped by the name checks).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
